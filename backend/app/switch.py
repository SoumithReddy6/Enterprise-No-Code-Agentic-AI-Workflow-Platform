"""Switch: choose exactly one of several named paths with ordered Condition predicates.

Each case is a full Condition, so numbers, text, membership, empty values and their named
errors behave exactly as they do in a Condition. The first true case wins and later cases
are not evaluated; no match selects `default`. A comparison error fails the node: it
never selects `default` and never tries the next case.

A Switch decides a business path, so it runs only in contract 2 and only on checked or
trusted values (see request_safety and compiler.request_contract_errors). A case id or
label grants no authority to the path behind it.
"""
from typing import Annotated

from pydantic import Field, StrictStr, field_validator, model_validator

from .conditions import ConditionConfig, evaluate
from .models import StrictModel

RESERVED = ('default', 'error')


class SwitchCase(StrictModel):
    id: Annotated[StrictStr, Field(pattern=r'^[A-Za-z][A-Za-z0-9_-]{0,63}$', title='Case id',
                                   description='Stable route handle. Generated by the editor; renaming the label keeps it.')]
    label: Annotated[StrictStr, Field(min_length=1, max_length=80, title='Label')]
    when: ConditionConfig

    @field_validator('id')
    @classmethod
    def not_reserved(cls, value):
        if value in RESERVED:raise ValueError(f'{value} is a reserved route; choose another case id.')
        return value

    @field_validator('label')
    @classmethod
    def nonblank(cls, value):
        if not value.strip():raise ValueError('A case label must not be blank.')
        return value


class SwitchConfig(StrictModel):
    cases: list[SwitchCase] = Field(min_length=1, max_length=15, title='Cases',
                                    description='Checked in order; the first matching case wins. No match takes Default.')

    @model_validator(mode='after')
    def unique_ids(self):
        ids = [case.id for case in self.cases]
        if len(set(ids)) != len(ids):raise ValueError('Case ids must be unique.')
        return self


def routes(config: SwitchConfig) -> tuple[str, ...]:
    return (*(case.id for case in config.cases), 'default')


def choose(value, config: SwitchConfig) -> str:
    for case in config.cases:
        if evaluate(value, case.when):
            return case.id
    return 'default'


async def switch_node(inputs, config: SwitchConfig, ctx):
    branch = choose(inputs['value'], config)
    from .observability import journal
    journal(event='switch.route', node_id=ctx.node_id, reason_code=branch)
    return {'branch': branch}
